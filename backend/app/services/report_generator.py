def _clean_reportlab_text(text: str) -> str:
    """
    Safely escapes raw text for ReportLab Paragraph XML parsing,
    preserving bold markdown tags and preventing XML parsing crashes
    on clinical symbols like '<', '>', '&'.
    """
    if not text:
        return ""
    # Escape XML entities
    escaped = html.escape(str(text))
    # Convert escaped markdown bold **text** to <b>text</b>
    formatted = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', escaped)
    # Strip markdown headers ### or ####
    formatted = re.sub(r'^#{1,6}\s*', '', formatted)
    return formatted

MANDATORY_DISCLAIMER = (
    "This report is generated by an AI-assisted clinical guideline navigation system "
    "and is intended for clinical decision support only. It does not replace professional "
    "medical judgment. All recommendations must be reviewed and validated by a qualified "
    "healthcare professional before clinical application."
)

class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute and render total page count ('Page X of Y').
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#6b5f83"))

        # Running Header
        self.drawString(54, letter[1] - 36, "Clinical Navigator — Dynamic Clinical Guideline Assessment Report")
        self.setStrokeColor(colors.HexColor("#e2d9f3"))
        self.setLineWidth(0.5)
        self.line(54, letter[1] - 42, letter[0] - 54, letter[1] - 42)

        # Running Footer
        self.line(54, 46, letter[0] - 54, 46)
        self.drawString(54, 34, "CONFIDENTIAL — Medical Legal Record for Authorized Clinical Personnel Only")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 54, 34, page_text)
        self.restoreState()


def generate_pdf_report(report_data: Dict[str, Any]) -> bytes:
    """
    Generates a high-quality multi-page PDF clinical decision assessment report.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=54,
        rightMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#1b122e"),
        spaceAfter=4
    )
    subtitle_style = ParagraphStyle(
        "ReportSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#5b21b6"),
        spaceAfter=12
    )
    h2_style = ParagraphStyle(
        "SectionHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=15,
        textColor=colors.HexColor("#2a184e"),
        spaceBefore=10,
        spaceAfter=6,
        keepWithNext=True
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#261c38")
    )
    body_bold = ParagraphStyle(
        "BodyBold",
        parent=body_style,
        fontName="Helvetica-Bold"
    )
    callout_style = ParagraphStyle(
        "CalloutText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13.5,
        textColor=colors.HexColor("#1b122e")
    )
    disclaimer_style = ParagraphStyle(
        "DisclaimerText",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#5c4f74")
    )

    story = []

    # Title Banner
    story.append(Paragraph("Clinical Guideline Assessment Report", title_style))
    story.append(Paragraph("Clinical Decision Support & Guideline Retrieval Record • Clinical Navigator CDSS", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#5b21b6"), spaceAfter=10))

    # Meta Overview Box
    now_str = report_data.get("generated_at") or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    clinician_name = report_data.get("clinician_name") or report_data.get("clinician_email") or "Authorized Healthcare Provider"
    decision_status = (report_data.get("decision_status") or "ACCEPTED").upper()

    status_color = colors.HexColor("#059669") # green
    if decision_status == "MODIFIED":
        status_color = colors.HexColor("#7c3aed") # purple
    elif decision_status == "REJECTED":
        status_color = colors.HexColor("#dc2626") # red

    meta_table_data = [
        [
            Paragraph("<b>Generated:</b> " + now_str, body_style),
            Paragraph("<b>Clinician:</b> " + clinician_name, body_style),
        ],
        [
            Paragraph("<b>Application:</b> Clinical Navigator CDSS v1.0", body_style),
            Paragraph(f"<b>Decision Status:</b> <font color='{status_color.hexval()}'><b>{decision_status}</b></font>", body_style)
        ]
    ]
    t_meta = Table(meta_table_data, colWidths=[250, 254])
    t_meta.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8f6fc")),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#ded5f0")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t_meta)
    story.append(Spacer(1, 12))

    # 1. Patient Details
    story.append(Paragraph("1. Patient Profile", h2_style))
    patient = report_data.get("patient") or {}
    p_name = patient.get("full_name") or patient.get("name") or "Unspecified Patient"
    p_code = patient.get("patient_code") or patient.get("patient_id") or "N/A"
    p_age = str(patient.get("age")) + " years" if patient.get("age") is not None else "Unrecorded"
    p_gender = patient.get("gender") or "Unrecorded"
    p_contact = patient.get("contact") or "Unrecorded"
    p_email = patient.get("email") or "Unrecorded"
    p_conditions = ", ".join(patient.get("medical_conditions", [])) or "None recorded"
    p_allergies = ", ".join(patient.get("allergies", [])) or "None recorded"
    p_medications = ", ".join(patient.get("medications", [])) or "None recorded"

    patient_table_data = [
        [Paragraph("<b>Full Name:</b>", body_style), Paragraph(p_name, body_style),
         Paragraph("<b>Patient Code:</b>", body_style), Paragraph(p_code, body_style)],
        [Paragraph("<b>Age:</b>", body_style), Paragraph(p_age, body_style),
         Paragraph("<b>Gender:</b>", body_style), Paragraph(p_gender, body_style)],
        [Paragraph("<b>Contact:</b>", body_style), Paragraph(p_contact, body_style),
         Paragraph("<b>Email:</b>", body_style), Paragraph(p_email, body_style)],
        [Paragraph("<b>Conditions:</b>", body_style), Paragraph(p_conditions, body_style),
         Paragraph("<b>Allergies:</b>", body_style), Paragraph(p_allergies, body_style)],
        [Paragraph("<b>Medications:</b>", body_style), Paragraph(p_medications, body_style),
         Paragraph("<b>Address:</b>", body_style), Paragraph(patient.get("address") or "Unrecorded", body_style)]
    ]
    t_patient = Table(patient_table_data, colWidths=[75, 175, 75, 179])
    t_patient.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#ffffff")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2d9f3")),
        ("PADDING", (0, 0), (-1, -1), 5),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(t_patient)
    story.append(Spacer(1, 12))

    # 2. Clinical Query
    story.append(Paragraph("2. Clinical Query", h2_style))
    query_text = report_data.get("question") or "No question recorded."
    q_table = Table([[Paragraph(_clean_reportlab_text(query_text), callout_style)]], colWidths=[504])
    q_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f5f3ff")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#7c3aed")),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(q_table)
    story.append(Spacer(1, 12))

    # 3. AI-Generated Guideline Recommendation
    story.append(Paragraph("3. AI-Assisted Recommendation (Evidence Synthesized)", h2_style))
    ai_answer = report_data.get("ai_answer") or "No recommendation generated."
    ai_paragraphs = [
        Paragraph(_clean_reportlab_text(p.strip()), body_style)
        for p in ai_answer.split("\n")
        if p.strip()
    ] or [Paragraph(_clean_reportlab_text(ai_answer), body_style)]
    
    ai_cell = []
    for p in ai_paragraphs:
        ai_cell.append(p)
        ai_cell.append(Spacer(1, 4))
    if ai_cell:
        ai_cell.pop() # remove last spacer

    ai_table = Table([[ai_cell]], colWidths=[504])
    ai_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fafafa")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#d4d4d8")),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(ai_table)
    story.append(Spacer(1, 12))

    # 4. Clinical Decision & Clinician Audit Trail
    story.append(Paragraph("4. Clinician Decision & Audit Record", h2_style))
    final_decision = report_data.get("final_decision") or (ai_answer if decision_status == "ACCEPTED" else "None")
    rejection_reason = report_data.get("rejection_reason")
    decision_time = report_data.get("decision_timestamp") or report_data.get("created_at") or now_str

    decision_rows = [
        [Paragraph("<b>Status:</b>", body_style), Paragraph(f"<font color='{status_color.hexval()}'><b>{decision_status}</b></font>", body_bold)],
        [Paragraph("<b>Recorded At:</b>", body_style), Paragraph(decision_time, body_style)],
    ]

    if decision_status == "MODIFIED":
        decision_rows.append([
            Paragraph("<b>Modified Clinical Directive:</b>", body_style),
            Paragraph(_clean_reportlab_text(final_decision), body_style)
        ])
    elif decision_status == "REJECTED":
        decision_rows.append([
            Paragraph("<b>Reason for Rejection:</b>", body_style),
            Paragraph(_clean_reportlab_text(rejection_reason or "Clinician chose not to adopt AI recommendation."), body_style)
        ])
    else:
        decision_rows.append([
            Paragraph("<b>Adopted Directive:</b>", body_style),
            Paragraph(_clean_reportlab_text(final_decision), body_style)
        ])

    t_decision = Table(decision_rows, colWidths=[120, 384])
    t_decision.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fdfcff")),
        ("BOX", (0, 0), (-1, -1), 1, status_color),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e4e4e7")),
        ("PADDING", (0, 0), (-1, -1), 6),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(t_decision)
    story.append(Spacer(1, 12))

    # 5. Retrieved Evidence & Guideline References
    story.append(Paragraph("5. Retrieved Evidence & Authoritative Citations", h2_style))
    sources = report_data.get("sources") or []

    if sources:
        evidence_data = [
            [
                Paragraph("<b>#</b>", body_bold),
                Paragraph("<b>Guideline Title</b>", body_bold),
                Paragraph("<b>Authority</b>", body_bold),
                Paragraph("<b>Page</b>", body_bold),
                Paragraph("<b>Excerpt / Excerpt Context</b>", body_bold),
            ]
        ]
        for idx, src in enumerate(sources, start=1):
            g_title = src.get("title") or "Clinical Guideline"
            org = src.get("organization") or "Authority"
            page = str(src.get("page") or src.get("page_number") or "N/A")
            excerpt = src.get("excerpt") or src.get("content") or ""
            if len(excerpt) > 280:
                excerpt = excerpt[:277] + "..."

            evidence_data.append([
                Paragraph(str(idx), body_style),
                Paragraph(_clean_reportlab_text(g_title), body_style),
                Paragraph(_clean_reportlab_text(org), body_style),
                Paragraph(page, body_style),
                Paragraph(_clean_reportlab_text(excerpt), body_style)
            ])

        t_evidence = Table(evidence_data, colWidths=[20, 140, 60, 35, 249])
        t_evidence.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#ede9fe")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#d8b4fe")),
            ("PADDING", (0, 0), (-1, -1), 4),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(t_evidence)
    else:
        story.append(Paragraph("<i>No specific guideline passages retrieved for this session.</i>", body_style))

    story.append(Spacer(1, 14))

    # 6. Mandatory Clinical Disclaimer Box
    disclaimer_table = Table([[
        Paragraph(f"<b>CLINICAL DISCLAIMER & REGULATORY NOTICE:</b><br/>{MANDATORY_DISCLAIMER}", disclaimer_style)
    ]], colWidths=[504])
    disclaimer_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fffbeb")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#f59e0b")),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(KeepTogether([disclaimer_table]))

    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()


def generate_docx_report(report_data: Dict[str, Any]) -> bytes:
    """
    Generates a professional editable Microsoft Word (.docx) assessment report.
    """
    doc = docx.Document()

    # Set 0.75-inch margins
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(0.75)
        section.bottom_margin = Inches(0.75)
        section.left_margin = Inches(0.75)
        section.right_margin = Inches(0.75)

    # Title
    title = doc.add_paragraph()
    r_title = title.add_run("Clinical Guideline Assessment Report")
    r_title.bold = True
    r_title.font.size = Pt(20)
    r_title.font.color.rgb = RGBColor(0x1B, 0x12, 0x2E)

    subtitle = doc.add_paragraph()
    r_sub = subtitle.add_run("Clinical Decision Support & Guideline Retrieval Record • Clinical Navigator CDSS")
    r_sub.font.size = Pt(10)
    r_sub.font.color.rgb = RGBColor(0x5B, 0x21, 0xB6)

    # Metadata Table
    now_str = report_data.get("generated_at") or datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    clinician_name = report_data.get("clinician_name") or report_data.get("clinician_email") or "Authorized Healthcare Provider"
    decision_status = (report_data.get("decision_status") or "ACCEPTED").upper()

    table_meta = doc.add_table(rows=2, cols=2)
    table_meta.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_meta.rows[0].cells[0].text = f"Report Generated: {now_str}"
    table_meta.rows[0].cells[1].text = f"Clinician: {clinician_name}"
    table_meta.rows[1].cells[0].text = "Application: Clinical Navigator CDSS v1.0"
    table_meta.rows[1].cells[1].text = f"Decision Status: {decision_status}"

    doc.add_paragraph()

    # 1. Patient Profile
    h1 = doc.add_heading("1. Patient Profile", level=2)
    patient = report_data.get("patient") or {}
    p_name = patient.get("full_name") or patient.get("name") or "Unspecified Patient"
    p_code = patient.get("patient_code") or patient.get("patient_id") or "N/A"
    p_age = str(patient.get("age")) + " years" if patient.get("age") is not None else "Unrecorded"
    p_gender = patient.get("gender") or "Unrecorded"
    p_contact = patient.get("contact") or "Unrecorded"
    p_email = patient.get("email") or "Unrecorded"
    p_conditions = ", ".join(patient.get("medical_conditions", [])) or "None recorded"
    p_allergies = ", ".join(patient.get("allergies", [])) or "None recorded"
    p_medications = ", ".join(patient.get("medications", [])) or "None recorded"

    p_table = doc.add_table(rows=5, cols=2)
    p_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    p_table.rows[0].cells[0].text = f"Full Name: {p_name}"
    p_table.rows[0].cells[1].text = f"Patient Code: {p_code}"
    p_table.rows[1].cells[0].text = f"Age: {p_age}"
    p_table.rows[1].cells[1].text = f"Gender: {p_gender}"
    p_table.rows[2].cells[0].text = f"Contact (India): {p_contact}"
    p_table.rows[2].cells[1].text = f"Email Address: {p_email}"
    p_table.rows[3].cells[0].text = f"Medical Conditions: {p_conditions}"
    p_table.rows[3].cells[1].text = f"Known Allergies: {p_allergies}"
    p_table.rows[4].cells[0].text = f"Active Medications: {p_medications}"
    p_table.rows[4].cells[1].text = f"Address: {patient.get('address') or 'Unrecorded'}"

    doc.add_paragraph()

    # 2. Clinical Query
    doc.add_heading("2. Clinical Query", level=2)
    q_para = doc.add_paragraph()
    q_run = q_para.add_run(report_data.get("question") or "No question recorded.")
    q_run.bold = True
    q_run.font.color.rgb = RGBColor(0x2A, 0x18, 0x4E)

    # 3. AI-Generated Recommendation
    doc.add_heading("3. AI-Assisted Recommendation (Evidence Synthesized)", level=2)
    ai_answer = report_data.get("ai_answer") or "No recommendation generated."
    doc.add_paragraph(ai_answer)

    # 4. Clinical Decision & Audit
    doc.add_heading("4. Clinician Decision & Audit Record", level=2)
    final_decision = report_data.get("final_decision") or (ai_answer if decision_status == "ACCEPTED" else "None")
    rejection_reason = report_data.get("rejection_reason")
    decision_time = report_data.get("decision_timestamp") or report_data.get("created_at") or now_str

    d_table = doc.add_table(rows=3, cols=2)
    d_table.alignment = WD_TABLE_ALIGNMENT.CENTER
    d_table.rows[0].cells[0].text = "Decision Status"
    d_table.rows[0].cells[1].text = decision_status
    d_table.rows[1].cells[0].text = "Recorded Timestamp"
    d_table.rows[1].cells[1].text = decision_time

    if decision_status == "MODIFIED":
        d_table.rows[2].cells[0].text = "Modified Clinical Directive"
        d_table.rows[2].cells[1].text = final_decision
    elif decision_status == "REJECTED":
        d_table.rows[2].cells[0].text = "Rejection Rationale"
        d_table.rows[2].cells[1].text = rejection_reason or "Clinician rejected recommendation."
    else:
        d_table.rows[2].cells[0].text = "Adopted Directive"
        d_table.rows[2].cells[1].text = final_decision

    doc.add_paragraph()

    # 5. Retrieved Evidence
    doc.add_heading("5. Retrieved Evidence & Authoritative Citations", level=2)
    sources = report_data.get("sources") or []
    if sources:
        e_table = doc.add_table(rows=len(sources) + 1, cols=4)
        e_table.alignment = WD_TABLE_ALIGNMENT.CENTER
        e_table.rows[0].cells[0].text = "Guideline Title"
        e_table.rows[0].cells[1].text = "Authority"
        e_table.rows[0].cells[2].text = "Page"
        e_table.rows[0].cells[3].text = "Retrieved Excerpt"

        for idx, src in enumerate(sources, start=1):
            e_table.rows[idx].cells[0].text = src.get("title") or "Guideline"
            e_table.rows[idx].cells[1].text = src.get("organization") or "Authority"
            e_table.rows[idx].cells[2].text = str(src.get("page") or src.get("page_number") or "N/A")
            excerpt = src.get("excerpt") or src.get("content") or ""
            e_table.rows[idx].cells[3].text = excerpt[:350]
    else:
        doc.add_paragraph("No specific guideline passages cited.")

    doc.add_paragraph()

    # 6. Clinical Disclaimer
    doc.add_heading("Clinical Disclaimer & Regulatory Notice", level=3)
    p_disc = doc.add_paragraph()
    r_disc = p_disc.add_run(MANDATORY_DISCLAIMER)
    r_disc.italic = True
    r_disc.font.size = Pt(8.5)
    r_disc.font.color.rgb = RGBColor(0x6B, 0x5F, 0x83)

    out_buf = io.BytesIO()
    doc.save(out_buf)
    return out_buf.getvalue()

